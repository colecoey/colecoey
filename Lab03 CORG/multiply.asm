.ORIG x3000

; = = = = = = = = = = = = = = = = =

LD R0, VAR_A
LD R1, VAR_B

JSR MULT

ST R0, PRODUCT

HALT

; = = = = = = = = = = = = = = = = =
VAR_A .FILL	#4
VAR_B .FILL #7
PRODUCT .FILL #0
; = = = = = = = = = = = = = = = = =

; = = = = = = = = = = = = = = = = =
MULT

ST R7, SAVE_R7_MULT

ST R0, FACTOR_1
ST R1, FACTOR_2

AND R0, R0, #0
ST R0, MULT_RESULT
ST R0, VAR_I_MULT

START_MULT_LOOP
LD R0, VAR_I_MULT
LD R1. FACTOR_2
NOT R1, R1
ADD R1, R1, #1
ADD R0, R0, R1
BRzp END_MULT_LOOP

LD R0, MULT_RESULT
LD R1, FACTOR_1
ADD R0, R0, R1
ST R0, MULT_RESULT

LD R0, VAR_I_MULT
ADD R0, R0, #1
ST R0, VAR_I_MULT

BRnzp START_MULT_LOOP
END_MULT_LOOP

LD R0, MULT_RESULT

LD R7, SAVE_R7_MULTQ
RET

SAVE_R7_MULT .FILL #0

FACTOR_1 .FILL #0
FACTOR_2 .FILL #0
MULT_RESULT .FILL #0
VAR_I_MULT .FILL #0

